/**
 * Eigene Pixel-Icons. Jede Zeile ist eine Pixelreihe:
 * '#' = Hauptfarbe (currentColor), '+' = Akzentfarbe, 'o' = Flüssigkeit, '.' = leer.
 */
function pixels(rows: string[], cls = 'px'): string {
  const w = Math.max(...rows.map((r) => r.length));
  const rects: string[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') {
        x++;
        continue;
      }
      let len = 1;
      while (row[x + len] === ch) len++;
      const fill = ch === '#' ? 'currentColor' : ch === '+' ? 'var(--accent)' : 'var(--liquid)';
      rects.push(`<rect x="${x}" y="${y}" width="${len}" height="1" fill="${fill}"${ch === 'o' ? ' class="liq"' : ''}/>`);
      x += len;
    }
  });
  return `<svg class="${cls}" viewBox="0 0 ${w} ${rows.length}" shape-rendering="crispEdges" aria-hidden="true">${rects.join('')}</svg>`;
}

